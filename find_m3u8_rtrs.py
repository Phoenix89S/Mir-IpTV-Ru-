# 3) Основная функция авто‑EPG
def apply_epg(channel_name: str):
    """
    Возвращает:
      tvg_id  — строка или None
      shift   — int или None
      title   — оригинальное название (НЕ меняем)
    """
    original_name = channel_name
    name_lower = channel_name.lower()

    # 0) Нормализация названия по твоему словарю
    for key, base_name in EPG_NAME_NORMALIZE.items():
        if key in name_lower:
            channel_name = base_name
            break

    # 1) Определяем смещение по городу/региону (ищем в ОРИГИНАЛЬНОМ названии)
    shift = None
    lower_orig = original_name.lower()
    for key, val in EPG_REGION_SHIFT.items():
        if key.lower() in lower_orig:
            shift = val
            break

    # 2) Определяем базовый канал → tvg-id
    tvg_id = None
    lower_norm = channel_name.lower()
    for base, epg_id in EPG_CHANNEL_BASE.items():
        if base.lower() in lower_norm:
            tvg_id = epg_id
            break

    return tvg_id, shift, original_name

