def build_playlist(merged_channels):
    """
    Формирует итоговый текст плейлиста:
    - #EXTM3U
    - блоки по кнопкам
    - сортировка внутри кнопки по твоей нумерации (1.0, 1.1, 1.2…)
    - проставление [OLD] и [MANUAL]
    """
    output = ['#EXTM3U url-tvg="http://epg.one/epg2.xml.gz" catchup="append" catchup-type="default" catchup-days="14" catchup-source="${url}&utc=${start}&lutc=${timestamp}" timeshift="0" tvg-rec="1" x-logos="https://logos.server/${tvg-id}.png" x-chno="auto" x-grouping="buttons" http-user-agent="Mozilla/5.0 (SmartTV; PhoenixEngine)" http-referrer="https://phoenix.local/" network-caching="2000" x-drm-system="none" x-origin="Phoenix Engine 2026" x-epg-provider="epg.one"']

    # Группировка по кнопкам
    grouped = defaultdict(list)

    for name, data in merged_channels.items():
        group = detect_group(name)
        grouped[group].append((name, data))

    # Сортировка кнопок по порядку (Кнопка 1, Кнопка 2, …)
    def button_sort_key(btn):
        try:
            return int(btn.replace("Кнопка ", ""))
        except:
            return 9999

    for button in sorted(grouped.keys(), key=button_sort_key):

        # Добавляем комментарий-кнопку
        output.append(f"\n# ===== {button} =====")

        # Сортировка внутри кнопки по твоей нумерации (1.0, 1.1, 1.2…)
        def channel_sort_key(item):
            name, data = item
            mapping = CHANNEL_GROUPS.get(button, {})
            for key, cname in mapping.items():
                if cname.lower() == name.lower():
                    # ключ вида "3.0.7" → [3, 0, 7]
                    return [int(x) for x in key.split(".")]
            return [9999]

        for name, data in sorted(grouped[button], key=channel_sort_key):

            meta = data["meta"]
            url = data["url"]

            # Пометка OLD
            if data["old"] and OLD_TAG not in meta:
                meta = meta.replace(",", f" {OLD_TAG},")

            # MANUAL не трогаем
            if data["manual"] and MANUAL_TAG not in meta:
                meta = meta.replace(",", f" {MANUAL_TAG},")

            # ============================
            #   EPG: применение движка
            # ============================
            tvg_id, shift, title = apply_epg(name)

            # Пересобираем meta с EPG-тегами
            new_meta = "#EXTINF:-1"

            if tvg_id:
                new_meta += f' tvg-id="{tvg_id}"'

            if shift is not None:
                new_meta += f' tvg-shift="{shift}"'

            # Добавляем MANUAL/OLD если они были
            if MANUAL_TAG in meta:
                new_meta += f' {MANUAL_TAG}'
            if OLD_TAG in meta:
                new_meta += f' {OLD_TAG}'

            # Финальное имя канала
            new_meta += f',{title}'

            meta = new_meta
            # ============================

            output.append(meta)
            output.append(url)

    return "\n".join(output)

